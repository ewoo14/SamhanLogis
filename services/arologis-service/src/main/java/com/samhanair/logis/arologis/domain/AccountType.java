package com.samhanair.logis.arologis.domain;

/**
 * 아로로지스 간이 계정과목 유형.
 *
 * <p>일반기업회계기준 표준계정과목 5분류이다(2026-06-09 개발책임자 지시로 자본 추가). 복식부기의
 * 차변/대변, 분개, 마감 개념은 사용하지 않으며 단식부기 현금출납장의 계정 분류로만 사용한다.
 */
public enum AccountType {

    /** 자산 (예: 현금, 보통예금, 차량운반구). */
    ASSET,

    /** 부채 (예: 미지급금, 단기차입금). */
    LIABILITY,

    /** 자본 (예: 자본금, 이익잉여금, 인출금). */
    EQUITY,

    /** 수입 (예: 운송수입, 용역매출). */
    INCOME,

    /** 지출/비용 (예: 급여, 유류비, 외주운송비). */
    EXPENSE
}
